import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { rtcConfiguration } from '../backend/rtc';
import { OutgoingIceQueue } from '../src/services/iceSignaling';

const defaultConfig = rtcConfiguration('alice', {});
assert.equal(defaultConfig.relayConfigured, false);
assert.equal(defaultConfig.iceServers.length, 1);
const env = { TURN_URLS: 'turn:relay.example:3478?transport=udp,turns:relay.example:5349?transport=tcp', TURN_SHARED_SECRET: 'test-secret-only' };
const config = rtcConfiguration('alice', env, 1700000000000);
const relay = config.iceServers[1];
assert.equal(config.relayConfigured, true);
assert.equal(relay.username, '1700003600:alice');
assert.equal(relay.credential, crypto.createHmac('sha1', env.TURN_SHARED_SECRET).update(relay.username!).digest('base64'));
assert.equal((relay.urls as string[]).length, 2);
assert.ok(!JSON.stringify(config).includes(env.TURN_SHARED_SECRET));
assert.throws(() => rtcConfiguration('alice', { TURN_URLS: env.TURN_URLS }));
assert.throws(() => rtcConfiguration('alice', { ...env, TURN_URLS: 'https://wrong.example' }));
const sent: RTCIceCandidateInit[] = [];
const queue = new OutgoingIceQueue(candidate => sent.push(candidate));
queue.add({ candidate: 'early' });
assert.equal(sent.length, 0, 'Do not send ICE before offer/answer');
queue.descriptionSent();
queue.add({ candidate: 'late' });
assert.deepEqual(sent.map(c => c.candidate), ['early', 'late']);
queue.reset();
queue.add({ candidate: 'restart' });
assert.equal(sent.length, 2, 'Hold restarted ICE until new SDP is sent');
queue.descriptionSent();
assert.equal(sent[2].candidate, 'restart');
queue.reset(); queue.add({ candidate: 'cancelled' }); queue.reset(); queue.descriptionSent();
assert.equal(sent.length, 3, 'Cancelled calls cannot leak queued ICE');
console.log('PASS: temporary TURN credentials, secret isolation, invalid config, SDP/ICE ordering, restart and cancellation');
