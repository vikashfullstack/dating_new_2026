import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ProfileMediaEditor } from '../src/components/ProfileMediaEditor';
import { ProfileDetailsModal } from '../src/components/ProfileDetailsModal';
import { validateProfileMedia, PHOTO_BYTES, VIDEO_BYTES } from '../src/utils/profileMedia';
import { discoveryProfiles } from '../backend/discovery';
import { initialCurrentUser, localSinglesData } from '../src/data/mockProfiles';

const photo = 'data:image/png;base64,aGVsbG8=';
const video = 'data:video/mp4;base64,aGVsbG8=';
assert.equal(validateProfileMedia([photo], [video]), null);
assert.equal(validateProfileMedia(['/src/assets/existing.jpg'], []), null);
assert.ok(validateProfileMedia([], []));
assert.ok(validateProfileMedia(null, []));
assert.ok(validateProfileMedia([photo], null));
assert.ok(validateProfileMedia(Array(9).fill(photo), []));
assert.ok(validateProfileMedia([photo], Array(4).fill(video)));
assert.ok(validateProfileMedia(['data:image/svg+xml;base64,aGVsbG8='], []));
assert.ok(validateProfileMedia(['javascript:alert(1)'], []));
const encoded = (type: string, bytes: number) => `data:${type};base64,${Buffer.alloc(bytes).toString('base64')}`;
assert.equal(validateProfileMedia([encoded('image/png', PHOTO_BYTES)], []), null);
assert.ok(validateProfileMedia([encoded('image/png', PHOTO_BYTES + 1)], []));
assert.ok(validateProfileMedia([photo], [encoded('video/mp4', VIDEO_BYTES + 1)]));
assert.ok(validateProfileMedia([photo], Array(3).fill(encoded('video/mp4', VIDEO_BYTES))));
const user = { ...initialCurrentUser, photos: [photo, photo], videos: [video] };
const gallery = renderToStaticMarkup(<ProfileMediaEditor currentUser={user} isLoggedIn onUpdateProfile={async () => true} />);
assert.ok(gallery.includes('Add photos') && gallery.includes('Add videos'));
assert.ok(gallery.includes('Make cover') && gallery.includes('Remove photo 2'));
assert.ok(gallery.includes('<video') && gallery.includes('Remove video 1'));
const single = renderToStaticMarkup(<ProfileMediaEditor currentUser={{ ...user, photos: [photo] }} isLoggedIn onUpdateProfile={async () => true} />);
assert.match(single, /disabled="" aria-label="Remove photo 1"/);
const details = renderToStaticMarkup(<ProfileDetailsModal profile={{ ...localSinglesData[0], videos: [video] }} onClose={() => {}} onLike={() => {}} onStartChat={() => {}} />);
assert.ok(details.includes('<video') && details.includes('controls=""'));
const publicProfile = discoveryProfiles([user], { ...initialCurrentUser, id: 'viewer' })[0];
assert.deepEqual(publicProfile.photos, user.photos);
assert.deepEqual(publicProfile.videos, user.videos);
assert.equal((publicProfile as any).email, undefined);
console.log('PASS: media types, count/size/total limits, last-photo protection, gallery controls, public media and video playback');
